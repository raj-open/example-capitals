import { describe, expect, it } from "vitest";

import { markerSize } from "../src/utils/markers.ts";

// ----------------------------------------------------------------
// TESTS
// ----------------------------------------------------------------

describe("markerSize", () => {
    it.each([
        [10, 32],
        [4, 32],
        [3.5, 16],
        [2, 8],
        [1.5, 4],
        [0, 4],
    ])("zoom %d → %dpx", (zoom, size) => {
        expect(markerSize(zoom)).toBe(size);
    });
});
